export type TranslationKey = (typeof TRANSLATION_KEYS)[number];

const KEY_SET: ReadonlySet<string> = new Set(TRANSLATION_KEYS);

export function isTranslationKey(value: unknown): value is TranslationKey {
  return typeof value === 'string' && KEY_SET.has(value);
}

/** `{name}`: the only placeholder shape a message may use. */
export const PLACEHOLDER_PATTERN = /\{([a-zA-Z_][a-zA-Z0-9_]*)\}/g;

/** The distinct placeholder names in a message, sorted. */
export function placeholderNames(message: string): string[] {
  return [...new Set([...message.matchAll(PLACEHOLDER_PATTERN)].map((match) => match[1]!))].sort();
}

/** Whether every brace in a message belongs to a well-formed `{name}` placeholder. */
export function hasOnlyNamedPlaceholders(message: string): boolean {
  return !/[{}]/.test(message.replace(PLACEHOLDER_PATTERN, ''));
}
